# ---------------------------------------------------------------- 算法

def apply_relation(base_id: int, rel_name: str) -> int:
    """根据基准类型 ID 和关系名称，在矩阵中反查出目标类型的 ID。"""
    if not 0 <= base_id < len(TYPES):
        raise ValueError(f"类型 ID 越界: {base_id}")
    row = RELATION_MATRIX[base_id]
    try:
        return row.index(rel_name)
    except ValueError:
        raise ValueError(f"类型 {TYPES[base_id]} 不存在关系 {rel_name!r}") from None


def get_relation_name(base_id: int, target_id: int) -> str:
    """查表获取两个类型 ID 之间的关系名称。"""
    return RELATION_MATRIX[base_id][target_id]


def resolve(base_id: int, relations: Iterable[str]) -> int:
    """把一串关系依次作用到基准类型上，返回最终类型 ID。

    例：resolve(NAME_TO_ID["ILE"], ["对偶", "激活"]) -> NAME_TO_ID["LII"]
    """
    current_id = base_id
    for rel in relations:
        current_id = apply_relation(current_id, rel)
    return current_id


def compose_relations(relations: Iterable[str], base_id: int = 0) -> str:
    """纯关系复合：不指定起点时也能算出「关系 -> 关系」。

    做法是拿 base_id（默认 ILE）当傀儡基底跑一遍复合，
    再用它与原基底的关系名把结果翻译回关系。
    """
    return get_relation_name(base_id, resolve(base_id, relations))
